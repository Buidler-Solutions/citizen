#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
OUTPUT_DIR="${1:-$REPO_ROOT/dist/runtime-stack}"
BINARY_PATH="$REPO_ROOT/target/release/citizen-node"
RUNTIME_DIR="$OUTPUT_DIR/node-runtime"
APPS_DIR="$OUTPUT_DIR/apps"

copy_tree() {
  local source_dir="$1"
  local destination_dir="$2"

  mkdir -p "$destination_dir"
  rsync -a \
    --exclude 'node_modules' \
    --exclude '.next' \
    --exclude 'dist' \
    --exclude 'build' \
    --exclude 'coverage' \
    --exclude '*.log' \
    --exclude '.DS_Store' \
    "$source_dir/" "$destination_dir/"
}

echo "[bundle] repo root: $REPO_ROOT"
echo "[bundle] output dir: $OUTPUT_DIR"

echo "[bundle] building citizen-node release binary"
cargo build --release -p citizen-node --manifest-path "$REPO_ROOT/Cargo.toml"

rm -rf "$OUTPUT_DIR"
mkdir -p "$RUNTIME_DIR/bin" "$RUNTIME_DIR/config" "$RUNTIME_DIR/docker" "$APPS_DIR"

cp "$BINARY_PATH" "$RUNTIME_DIR/bin/citizen-node"
cp "$REPO_ROOT/config/localnet/validator-alpha.toml" "$RUNTIME_DIR/config/node.toml"

# The runtime bundle is a local/dev artifact. Ensure the starter config can
# boot without requiring an external signed admission manifest.
TEMP_NODE_CONFIG="$(mktemp)"
{
  echo "# Added by scripts/package_runtime_stack.sh for local runtime bundles."
  echo "# IMPORTANT: this bundle is for local/dev use and does not include a signed"
  echo "# admission manifest artifact. Production/staged environments should set"
  echo "# manifest_enforce = true and provide manifest_path to a signed manifest JSON."
  echo "manifest_enforce = false"
  cat "$RUNTIME_DIR/config/node.toml"
} > "$TEMP_NODE_CONFIG"
mv "$TEMP_NODE_CONFIG" "$RUNTIME_DIR/config/node.toml"

cp "$REPO_ROOT/deploy/runtime-stack/Dockerfile" "$RUNTIME_DIR/docker/Dockerfile"
cp "$REPO_ROOT/deploy/runtime-stack/docker-compose.yml" "$RUNTIME_DIR/docker/docker-compose.yml"
cp "$REPO_ROOT/deploy/runtime-stack/run-node.sh" "$RUNTIME_DIR/run-node.sh"
chmod +x "$RUNTIME_DIR/run-node.sh"

echo "[bundle] copying wallet CLI"
copy_tree "$REPO_ROOT/wallet/cli" "$APPS_DIR/wallet-cli"

echo "[bundle] copying explorer"
copy_tree "$REPO_ROOT/explorer" "$APPS_DIR/explorer"

echo "[bundle] copying dApp implementation"
copy_tree "$REPO_ROOT/dapp" "$APPS_DIR/dapp"

echo "[bundle] copying demo app"
copy_tree "$REPO_ROOT/demo" "$APPS_DIR/demo"

cat > "$OUTPUT_DIR/README.md" <<'BUNDLE_README'
# Runtime Stack Bundle

This bundle is generated by `scripts/package_runtime_stack.sh` and is intentionally separated from the monorepo source tree.

## Included artifacts

- `node-runtime/bin/citizen-node`: compiled node runtime binary.
- `node-runtime/config/node.toml`: starter config copied from localnet template.
- `node-runtime/run-node.sh`: CLI wrapper command for starting the runtime directly.
- `node-runtime/docker/`: Docker image + Compose definition for running the compiled runtime in a container.
- `apps/wallet-cli`: wallet CLI copy.
- `apps/explorer`: blockchain explorer copy.
- `apps/dapp`: dApp implementation copy.
- `apps/demo`: demo application copy.

## Run the runtime directly

```bash
cd node-runtime
./run-node.sh ./config/node.toml
```

## Run the runtime in Docker

```bash
cd node-runtime/docker
docker compose up --build
```

## Admission manifest note

The packaged `node-runtime/config/node.toml` sets `manifest_enforce = false`
for local/dev convenience because this runtime bundle does not ship with a
signed admission manifest JSON.

For shared/staged/production environments, re-enable admission enforcement:

1. Set `manifest_enforce = true` in `node-runtime/config/node.toml`.
2. Add `manifest_path = "/path/to/signed-manifest.json"`.
3. Ensure the manifest includes:
   - `payload.network_id`, `payload.genesis_hash`, `payload.boot_nodes`
   - `payload.validator_allowlist` (`validator_id` + `public_key` entries)
   - `payload.issued_at`, `payload.version`, `payload.manifest_id`
   - one or more trusted `signatures` over the canonical payload
BUNDLE_README

echo "[bundle] done"
echo "[bundle] generated stack at: $OUTPUT_DIR"
